def env_bool(name, default=False):
    """Читает булево значение из переменной окружения."""
    return os.getenv(name, str(default)).strip().lower() in ("1", "true", "yes", "on")


DEBUG = env_bool("DJANGO_DEBUG", default=True)

SECRET_KEY = os.getenv("DJANGO_SECRET_KEY")
if not SECRET_KEY:
    if DEBUG:
        # В режиме разработки генерируем временный ключ, чтобы приложение
        # запускалось без ручной настройки. В продакшене (DEBUG=False) ключ
        # обязателен и должен передаваться через переменную окружения.
        SECRET_KEY = get_random_secret_key()
    else:
        raise ImproperlyConfigured(
            "Переменная окружения DJANGO_SECRET_KEY обязательна при DEBUG=False"
        )

